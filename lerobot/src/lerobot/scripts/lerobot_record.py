@dataclass
class DatasetRecordConfig:
    # Dataset identifier. By convention it should match '{hf_username}/{dataset_name}' (e.g. `lerobot/test`).
    repo_id: str
    # A short but accurate description of the task performed during the recording (e.g. "Pick the Lego block and drop it in the box on the right.")
    single_task: str
    # Root directory where the dataset will be stored (e.g. 'dataset/path').
    root: str | Path | None = None
    # Limit the frames per second.
    fps: int = 30
    # Number of seconds for data recording for each episode.
    episode_time_s: int | float = 60
    # Number of seconds for resetting the environment after each episode.
    reset_time_s: int | float = 60
    # Number of episodes to record.
    num_episodes: int = 50
    # Encode frames in the dataset into video
    video: bool = True
    # Upload dataset to Hugging Face hub.
    push_to_hub: bool = True
    # Upload on private repository on the Hugging Face hub.
    private: bool = False
    # Add tags to your dataset on the hub.
    tags: list[str] | None = None
    # Number of subprocesses handling the saving of frames as PNG. Set to 0 to use threads only;
    # set to ≥1 to use subprocesses, each using threads to write images. The best number of processes
    # and threads depends on your system. We recommend 4 threads per camera with 0 processes.
    # If fps is unstable, adjust the thread count. If still unstable, try using 1 or more subprocesses.
    num_image_writer_processes: int = 0
    # Number of threads writing the frames as png images on disk, per camera.
    # Too many threads might cause unstable teleoperation fps due to main thread being blocked.
    # Not enough threads might cause low camera fps.
    num_image_writer_threads_per_camera: int = 4
    # Number of episodes to record before batch encoding videos
    # Set to 1 for immediate encoding (default behavior), or higher for batched encoding
    video_encoding_batch_size: int = 1
    # H.264 is fast and does not emit SVT-AV1's native stderr banner per episode.
    vcodec: str = "h264"
    # Enable streaming video encoding: encode frames in real-time during capture
    # instead of writing PNG images first. Makes save_episode() near-instant.
    streaming_encoding: bool = False
    # Maximum number of frames to buffer per camera when using streaming encoding.
    encoder_queue_maxsize: int = 30
    # Number of threads per encoder instance. None = codec default.
    encoder_threads: int | None = None
    # Rename map for the observation to override the image and state keys
    rename_map: dict[str, str] = field(default_factory=dict)

    def __post_init__(self):
        if self.single_task is None:
            raise ValueError("You need to provide a task as argument in `single_task`.")


@dataclass
class RecordConfig:
    robot: RobotConfig
    dataset: DatasetRecordConfig
    # Whether to control the robot with a teleoperator
    teleop: TeleoperatorConfig | None = None
    # Whether to control the robot with a policy
    policy: PreTrainedConfig | None = None
    # Opt-in joint reference limits for B601 policy inference; teleop is untouched.
    policy_motion: PolicyMotionConfig | None = None
    # Display all cameras on screen
    display_data: bool = False
    # Show only connected cameras in Rerun, without state/action or unused sensor panels.
    display_cameras_only: bool = False
    # Display data on a remote Rerun server
    display_ip: str | None = None
    # Port of the remote Rerun server
    display_port: int | None = None
    # Whether to  display compressed images in Rerun
    display_compressed_images: bool = False
    # Display B601 cameras and tactile sensors in an OpenCV window.
    opencv_preview: bool = False
    # Use vocal synthesis to read events.
    play_sounds: bool = True
    # Resume recording on an existing dataset.
    resume: bool = False
    # Disable dataset creation, frame buffering, video encoding and upload for policy-only inference.
    recording_enabled: bool = True
    # When true, episodes are controlled manually with the keyboard:
    # `c` starts an episode, `s` stops and commits it, `backspace` immediately discards it.
    manual_episode_control: bool = False

    def __post_init__(self):
        # HACK: We parse again the cli args here to get the pretrained path if there was one.
        policy_path = parser.get_path_arg("policy")

        if policy_path:
            cli_overrides = parser.get_cli_overrides("policy")

            self.policy = PreTrainedConfig.from_pretrained(policy_path, cli_overrides=cli_overrides)
            self.policy.pretrained_path = policy_path

        if self.teleop is None and self.policy is None:
            raise ValueError("Choose a policy, a teleoperator or both to control the robot")
        if self.policy_motion is not None and (self.policy is None or self.teleop is not None):
            raise ValueError("policy_motion is only supported for policy-only inference.")
        if not self.recording_enabled and (self.policy is None or self.teleop is not None):
            raise ValueError("recording_enabled=false is only supported for policy-only inference.")

    @classmethod
    def __get_path_fields__(cls) -> list[str]:
        """This enables the parser to load config from the policy using `--policy.path=local/dir`"""
        return ["policy"]


def _print_recording_episode(episode_index: int, total_episodes: int) -> None:
    print(f"\033[92mEpisode {episode_index}/{total_episodes}\033[0m", flush=True)


def _print_manual_controls(*, home_enabled: bool = False, recording_enabled: bool = True) -> None:
    if not recording_enabled:
        home_control = "h=return Home, " if home_enabled else ""
        print(
            "\033[92mManual inference (recording disabled): c=start, s=stop, "
            f"{home_control}backspace=stop, esc=exit.\033[0m",
            flush=True,
        )
        return
    home_control = "h=return Home and discard unsaved episode, " if home_enabled else ""
    print(
        "\033[92mManual recording: c=start episode, s=save episode, "
        f"{home_control}backspace=discard episode, esc=exit.\033[0m",
        flush=True,
    )


def _handle_policy_home(robot, dataset, events, policy, preprocessor, postprocessor) -> bool:
    """Handle Home outside record_loop, after its policy motion session has closed."""
    if not events.get("home_requested"):
        return False
    events["home_in_progress"] = True
    try:
        print("Returning Home (connection startup pose)...", flush=True)
        for processor in (policy, preprocessor, postprocessor):
            if processor is not None:
                processor.reset()
        if robot.reset_to_initial_position() is False:
            raise ReturnToInitialPositionError("Robot failed to return Home; inference will not resume.")
        if dataset is not None and dataset.has_pending_frames():
            dataset.clear_episode_buffer()
        print(
            "Home reached. Unsaved episode discarded; press c to start again."
            if dataset is not None else "Home reached. Press c to start inference again.",
            flush=True,
        )
    finally:
        # A c/s press before or during Home must never resume an old prediction.
        # Keep stop_recording intact so Esc still exits during the return.
        for key in (
            "home_requested", "start_episode", "stop_episode", "exit_early",
            "delete_last_episode", "rerecord_episode",
        ):
            events[key] = False
        events["home_in_progress"] = False
    return True


def _initial_recorded_episodes(dataset: LeRobotDataset) -> int:
    return int(getattr(dataset, "num_episodes", getattr(dataset.meta, "total_episodes", 0)))


def _add_auxiliary_policy_observations(
    robot: Robot, obs_processed: RobotObservation, observation_frame: dict[str, Any]
) -> dict[str, Any]:
    policy_frame = dict(observation_frame)
    for key, feature in robot.observation_features.items():
        if isinstance(feature, PolicyFeature) and feature.type is FeatureType.AUXILIARY:
            policy_frame[f"{OBS_STR}.{key}"] = obs_processed[key]
    return policy_frame


def _recover_observation_source(
    *,
    robot: Robot,
    dataset: LeRobotDataset | None,
    events: dict,
    error: RecoverableObservationError,
    play_sounds: bool,
    discard_episode: bool,
) -> bool:
    """Discard an interrupted episode and wait until the observation source recovers."""
    if discard_episode and dataset is not None and dataset.has_pending_frames():
        dataset.clear_episode_buffer()
    events["delete_last_episode"] = False
    events["exit_early"] = False
    events["stop_episode"] = False
    events["start_episode"] = False

    message = f"Observation failed: {error}"
    if discard_episode and dataset is not None:
        message += ". Discarded the current episode."
    logging.error(message)
    log_say(message, play_sounds)

    recover = getattr(robot, "recover_observation", None)
    if recover is None:
        raise error

    while not events["stop_recording"]:
        try:
            recover()
            logging.info("Observation source recovered; ready for the next episode.")
            log_say("Observation recovered. Ready for the next episode.", play_sounds)
            return True
        except (RecoverableObservationError, OSError) as recovery_error:
            logging.warning("Observation recovery failed; retrying in 1 second: %s", recovery_error)
            time.sleep(1.0)
    return False


""" --------------- record_loop() data flow --------------------------
       [ Robot ]
           V
     [ robot.get_observation() ] ---> raw_obs
           V
     [ robot_observation_processor ] ---> processed_obs
           V
     .-----( ACTION LOGIC )------------------.
     V                                       V
     [ From Teleoperator ]                   [ From Policy ]
     |                                       |
     |  [teleop.get_action] -> raw_action    |   [predict_action]
     |          |                            |          |
     |          V                            |          V
     | [teleop_action_processor]             |          |
     |          |                            |          |
     '---> processed_teleop_action           '---> processed_policy_action
     |                                       |
     '-------------------------.-------------'
                               V
                  [ robot_action_processor ] --> robot_action_to_send
                               V
                    [ robot.send_action() ] -- (Robot Executes)
                               V
                    ( Save to Dataset )
                               V
                  ( Rerun Log / Loop Wait )
"""


@safe_stop_image_writer
def record_loop(
    robot: Robot,
    events: dict,
    fps: int,
    teleop_action_processor: RobotProcessorPipeline[
        tuple[RobotAction, RobotObservation], RobotAction
    ],  # runs after teleop
    robot_action_processor: RobotProcessorPipeline[
        tuple[RobotAction, RobotObservation], RobotAction
    ],  # runs before robot
    robot_observation_processor: RobotProcessorPipeline[
        RobotObservation, RobotObservation
    ],  # runs after robot
    dataset: LeRobotDataset | None = None,
    teleop: Teleoperator | None = None,
    policy: PreTrainedPolicy | None = None,
    preprocessor: PolicyProcessorPipeline[dict[str, Any], dict[str, Any]] | None = None,
    postprocessor: PolicyProcessorPipeline[PolicyAction, PolicyAction] | None = None,
    control_time_s: int | None = None,
    single_task: str | None = None,
    display_data: bool = False,
    display_compressed_images: bool = False,
    opencv_preview: B601OpenCVPreview | None = None,
    manual_episode_control: bool = False,
    wait_for_episode_start: bool = False,
    record_frames: bool = True,
    quiet_no_action: bool = False,
    display_camera_names: tuple[str, ...] | None = None,
    policy_motion: PolicyMotionConfig | None = None,
    dataset_features: dict[str, dict] | None = None,
):
    if dataset is not None and dataset.fps != fps:
        raise ValueError(f"The dataset fps should be equal to requested fps ({dataset.fps} != {fps}).")
    features = dataset.features if dataset is not None else dataset_features
    if policy is not None and features is None:
        raise ValueError("Policy inference requires feature names even when recording is disabled.")

    with policy_motion_session(robot, policy_motion if policy is not None else None, fps):
        gripper_coordinator = PolicyGripperCoordinator(policy_motion if policy is not None else None)
        handover_release = PolicyHandoverRelease(
            policy_motion.handover_release if policy is not None and policy_motion is not None else None,
            policy_motion.gripper_closed_feedback if policy_motion is not None else 0.9,
        )
        # Reset policy and processor if they are provided
        if policy is not None and preprocessor is not None and postprocessor is not None:
            policy.reset()
            preprocessor.reset()
            postprocessor.reset()

        timestamp = 0
        start_episode_t = time.perf_counter()
        while control_time_s is None or timestamp < control_time_s:
            start_loop_t = time.perf_counter()

            if manual_episode_control and events.get("home_requested"):
                break

            if wait_for_episode_start and events["start_episode"]:
                events["exit_early"] = False
                break

            if manual_episode_control and events["delete_last_episode"]:
                events["exit_early"] = False
                break

            if manual_episode_control and events["stop_episode"]:
                # Leave stop_episode set so the outer manual-control state machine commits this episode.
                events["exit_early"] = False
                break

            if events["exit_early"]:
                events["exit_early"] = False
                break

            # Get robot observation
            obs = robot.get_observation()
            if isinstance(teleop, Teleoperator):
                sync_teleoperator_control_reference(teleop, robot)

            # Applies a pipeline to the raw robot observation, default is IdentityProcessor
            obs_processed = robot_observation_processor(obs)

            if opencv_preview is not None and not opencv_preview.update(obs_processed):
                events["stop_recording"] = True
                break

            if policy is not None or dataset is not None:
                observation_frame = build_dataset_frame(features, obs_processed, prefix=OBS_STR)

            # Get action from either policy or teleop
            if policy is not None and preprocessor is not None and postprocessor is not None:
                policy_observation_frame = _add_auxiliary_policy_observations(
                    robot, obs_processed, observation_frame
                )
                action_values = predict_action(
                    observation=policy_observation_frame,
                    policy=policy,
                    device=get_safe_torch_device(policy.config.device),
                    preprocessor=preprocessor,
                    postprocessor=postprocessor,
                    use_amp=policy.config.use_amp,
                    task=single_task,
                    robot_type=robot.robot_type,
                )

                act_processed_policy: RobotAction = make_robot_action(action_values, features)
                act_processed_policy = decode_policy_grippers(act_processed_policy, policy_motion)
                act_processed_policy = handover_release.apply(act_processed_policy, obs_processed)
                act_processed_policy = gripper_coordinator.apply(act_processed_policy, obs_processed)

            elif policy is None and isinstance(teleop, Teleoperator):
                if teleoperator_reset_requested(teleop):
                    logging.info("Teleoperator requested a return to the initial robot position.")
                    reset_robot_from_teleoperator(teleop, robot)
                    timestamp = time.perf_counter() - start_episode_t
                    continue
                act = teleop.get_action()
                sync_teleoperator_clutch(teleop, robot)

                # Applies a pipeline to the raw teleop action, default is IdentityProcessor
                act_processed_teleop = teleop_action_processor((act, obs))

            else:
                if not quiet_no_action:
                    logging.info(
                        "No policy or teleoperator provided, skipping action generation."
                        "This is likely to happen when resetting the environment without a teleop device."
                        "The robot won't be at its rest position at the start of the next episode."
                    )
                precise_sleep(1 / fps)
                timestamp = time.perf_counter() - start_episode_t
                continue

            # Applies a pipeline to the action, default is IdentityProcessor
            if policy is not None and act_processed_policy is not None:
                action_values = act_processed_policy
                robot_action_to_send = robot_action_processor((act_processed_policy, obs))
            else:
                action_values = act_processed_teleop
                robot_action_to_send = robot_action_processor((act_processed_teleop, obs))

            # Send action to robot
            # Action can eventually be clipped using `max_relative_target`,
            # so action actually sent is saved in the dataset. action = postprocessor.process(action)
            # TODO(steven, pepijn, adil): we should use a pipeline step to clip the action, so the sent action is the action that we input to the robot.
            # The key may arrive during a slow prediction or action processor.
            if manual_episode_control and events.get("home_requested"):
                break
            sent_action = robot.send_action(robot_action_to_send)
            if policy is None and isinstance(teleop, Teleoperator):
                handle_rejected_robot_action(teleop, robot)

            # Write to dataset
            if dataset is not None and record_frames:
                action_frame = build_dataset_frame(dataset.features, sent_action, prefix=ACTION)
                frame = {**observation_frame, **action_frame, "task": single_task}
                dataset.add_frame(frame)

            if display_data:
                log_rerun_data(
                    observation=obs_processed,
                    action=sent_action,
                    compress_images=display_compressed_images,
                    camera_names=display_camera_names,
                )

            dt_s = time.perf_counter() - start_loop_t
            precise_sleep(max(1 / fps - dt_s, 0.0))

            timestamp = time.perf_counter() - start_episode_t


@parser.wrap()
def record(cfg: RecordConfig) -> LeRobotDataset | None:
    init_logging()
    install_cleanup_signal_handlers()
    with rerun_session("recording", enabled=cfg.display_data, ip=cfg.display_ip, port=cfg.display_port):
        return _record(cfg)


def _record(cfg: RecordConfig) -> LeRobotDataset | None:
    display_compressed_images = (
        True
        if (cfg.display_data and cfg.display_ip is not None and cfg.display_port is not None)
        else cfg.display_compressed_images
    )

    robot = make_robot_from_config(cfg.robot)
    teleop = make_teleoperator_from_config(cfg.teleop) if cfg.teleop is not None else None

    teleop_action_processor, robot_action_processor, robot_observation_processor = make_default_processors()

    dataset_features = combine_feature_dicts(
        aggregate_pipeline_dataset_features(
            pipeline=teleop_action_processor,
            initial_features=create_initial_features(
                action=robot.action_features
            ),  # TODO(steven, pepijn): in future this should be come from teleop or policy
            use_videos=cfg.dataset.video,
        ),
        aggregate_pipeline_dataset_features(
            pipeline=robot_observation_processor,
            initial_features=create_initial_features(observation=robot.observation_features),
            use_videos=cfg.dataset.video,
        ),
    )

    if cfg.policy is not None:
        if cfg.policy_motion is not None and (
            not callable(getattr(robot, "set_policy_motion_limits", None))
            or cfg.robot.control_mode.lower() != "pos_vel"
        ):
            raise ValueError("policy_motion requires the B601 POS_VEL policy controller.")
        if not cfg.policy.pretrained_path:
            raise ValueError("Hardware inference with lerobot-record requires policy.pretrained_path")
        checkpoint_cfg = PreTrainedConfig.from_pretrained(cfg.policy.pretrained_path)
        validate_policy_robot_features(checkpoint_cfg, dataset_features, cfg.dataset.rename_map)

    dataset = None
    listener = None
    opencv_preview = None
    cleanup_error: Exception | None = None

    try:
        if not cfg.recording_enabled:
            # Checkpoint processors own normalization. Only feature names/shapes
            # are needed here; do not open even an existing evaluation dataset.
            policy_metadata = SimpleNamespace(features=dataset_features)
        elif cfg.resume:
            dataset = LeRobotDataset(
                cfg.dataset.repo_id,
                root=cfg.dataset.root,
                batch_encoding_size=cfg.dataset.video_encoding_batch_size,
                vcodec=cfg.dataset.vcodec,
                streaming_encoding=cfg.dataset.streaming_encoding,
                encoder_queue_maxsize=cfg.dataset.encoder_queue_maxsize,
                encoder_threads=cfg.dataset.encoder_threads,
            )

            if (
                not cfg.dataset.streaming_encoding
                and hasattr(robot, "cameras")
                and len(robot.cameras) > 0
            ):
                dataset.start_image_writer(
                    num_processes=cfg.dataset.num_image_writer_processes,
                    num_threads=cfg.dataset.num_image_writer_threads_per_camera * len(robot.cameras),
                )
            sanity_check_dataset_robot_compatibility(dataset, robot, cfg.dataset.fps, dataset_features)
        else:
            # Create empty dataset or load existing saved episodes
            sanity_check_dataset_name(cfg.dataset.repo_id, cfg.policy)
            dataset = LeRobotDataset.create(
                cfg.dataset.repo_id,
                cfg.dataset.fps,
                root=cfg.dataset.root,
                robot_type=robot.name,
                features=dataset_features,
                use_videos=cfg.dataset.video,
                image_writer_processes=cfg.dataset.num_image_writer_processes,
                image_writer_threads=cfg.dataset.num_image_writer_threads_per_camera * len(robot.cameras),
                batch_encoding_size=cfg.dataset.video_encoding_batch_size,
                vcodec=cfg.dataset.vcodec,
                streaming_encoding=cfg.dataset.streaming_encoding,
                encoder_queue_maxsize=cfg.dataset.encoder_queue_maxsize,
                encoder_threads=cfg.dataset.encoder_threads,
            )

        # Load pretrained policy
        if dataset is not None:
            policy_metadata = dataset.meta
        policy = None if cfg.policy is None else make_policy(cfg.policy, ds_meta=policy_metadata)
        preprocessor = None
        postprocessor = None
        if cfg.policy is not None:
            preprocessor, postprocessor = make_pre_post_processors(
                policy_cfg=cfg.policy,
                pretrained_path=cfg.policy.pretrained_path,
                dataset_stats=(
                    rename_stats(dataset.meta.stats, cfg.dataset.rename_map) if dataset is not None else None
                ),
                preprocessor_overrides={
                    "device_processor": {"device": cfg.policy.device},
                    "rename_observations_processor": {"rename_map": cfg.dataset.rename_map},
                },
            )

        robot.connect()
        display_camera_names = None
        if cfg.display_data and cfg.display_cameras_only:
            display_camera_names = tuple(
                name for name, camera in robot.cameras.items() if camera.is_connected
            )
            configure_rerun_camera_views(display_camera_names)
        if teleop is not None:
            connect_teleoperator(teleop, robot)
        if cfg.opencv_preview:
            opencv_preview = B601OpenCVPreview()

        home_enabled = (
            cfg.manual_episode_control
            and policy is not None
            and teleop is None
            and callable(getattr(robot, "reset_to_initial_position", None))
        )
        listener, events = init_keyboard_listener(enable_home=home_enabled)

        with VideoEncodingManager(dataset) if dataset is not None else nullcontext():
            recorded_episodes = _initial_recorded_episodes(dataset) if dataset is not None else 0
            if cfg.manual_episode_control:
                _print_manual_controls(
                    home_enabled=home_enabled,
                    recording_enabled=cfg.recording_enabled,
                )
                policy_only_eval = policy is not None and teleop is None
                waiting_policy = None if policy_only_eval else policy
                waiting_preprocessor = None if policy_only_eval else preprocessor
                waiting_postprocessor = None if policy_only_eval else postprocessor

                while (
                    (dataset is None or recorded_episodes < cfg.dataset.num_episodes)
                    and not events["stop_recording"]
                ):
                    try:
                        record_loop(
                            robot=robot,
                            events=events,
                            fps=cfg.dataset.fps,
                            teleop_action_processor=teleop_action_processor,
                            robot_action_processor=robot_action_processor,
                            robot_observation_processor=robot_observation_processor,
                            teleop=teleop,
                            policy=waiting_policy,
                            policy_motion=cfg.policy_motion,
                            preprocessor=waiting_preprocessor,
                            postprocessor=waiting_postprocessor,
                            dataset=dataset,
                            control_time_s=None,
                            single_task=cfg.dataset.single_task,
                            display_data=cfg.display_data,
                            display_camera_names=display_camera_names,
                            display_compressed_images=display_compressed_images,
                            opencv_preview=opencv_preview,
                            manual_episode_control=True,
                            wait_for_episode_start=True,
                            record_frames=False,
                            quiet_no_action=policy_only_eval,
                        )
                    except RecoverableObservationError as error:
                        if not _recover_observation_source(
                            robot=robot,
                            dataset=dataset,
                            events=events,
                            error=error,
                            play_sounds=cfg.play_sounds,
                            discard_episode=False,
                        ):
                            break
                        continue

                    if events["stop_recording"]:
                        break
                    if _handle_policy_home(robot, dataset, events, policy, preprocessor, postprocessor):
                        continue
                    if events["delete_last_episode"]:
                        events["delete_last_episode"] = False
                        events["exit_early"] = False
                        events["stop_episode"] = False
                        continue

                    if events["stop_episode"]:
                        events["stop_episode"] = False
                        events["exit_early"] = False
                        continue

                    if not events["start_episode"]:
                        events["exit_early"] = False
                        continue

                    events["start_episode"] = False

                    if dataset is not None:
                        _print_recording_episode(recorded_episodes + 1, cfg.dataset.num_episodes)
                    else:
                        print("Inference started (recording disabled).", flush=True)
                    try:
                        record_loop(
                            robot=robot,
                            events=events,
                            fps=cfg.dataset.fps,
                            teleop_action_processor=teleop_action_processor,
                            robot_action_processor=robot_action_processor,
                            robot_observation_processor=robot_observation_processor,
                            teleop=teleop,
                            policy=policy,
                            policy_motion=cfg.policy_motion,
                            dataset_features=dataset_features,
                            preprocessor=preprocessor,
                            postprocessor=postprocessor,
                            dataset=dataset,
                            control_time_s=None,
                            single_task=cfg.dataset.single_task,
                            display_data=cfg.display_data,
                            display_camera_names=display_camera_names,
                            display_compressed_images=display_compressed_images,
                            opencv_preview=opencv_preview,
                            manual_episode_control=True,
                        )
                    except RecoverableObservationError as error:
                        if not _recover_observation_source(
                            robot=robot,
                            dataset=dataset,
                            events=events,
                            error=error,
                            play_sounds=cfg.play_sounds,
                            discard_episode=True,
                        ):
                            break
                        continue

                    if _handle_policy_home(robot, dataset, events, policy, preprocessor, postprocessor):
                        continue

                    discard_requested = events["delete_last_episode"]
                    save_requested = events["stop_episode"] and not events["stop_recording"]
                    events["delete_last_episode"] = False
                    events["exit_early"] = False
                    events["stop_episode"] = False
                    events["start_episode"] = False

                    if dataset is None:
                        if not events["stop_recording"]:
                            print("Inference stopped (no data saved).", flush=True)
                    elif dataset.has_pending_frames():
                        if discard_requested or not save_requested:
                            dataset.clear_episode_buffer()
                            if discard_requested:
                                log_say("Discarded the current episode", cfg.play_sounds)
                            else:
                                log_say("Discarded the uncommitted episode", cfg.play_sounds)
                        else:
                            episode_metadata = (
                                robot.get_episode_metadata()
                                if hasattr(robot, "get_episode_metadata")
                                else None
                            )
                            dataset.save_episode(episode_metadata=episode_metadata)
                            recorded_episodes += 1
                            log_say("Episode saved. It can no longer be deleted with backspace.", cfg.play_sounds)
            else:
                while recorded_episodes < cfg.dataset.num_episodes and not events["stop_recording"]:
                    log_say(
                        f"{'Recording episode' if cfg.recording_enabled else 'Inference run'} "
                        f"{recorded_episodes + 1}/{cfg.dataset.num_episodes}",
                        cfg.play_sounds,
                    )
                    try:
                        record_loop(
                            robot=robot,
                            events=events,
                            fps=cfg.dataset.fps,
                            teleop_action_processor=teleop_action_processor,
                            robot_action_processor=robot_action_processor,
                            robot_observation_processor=robot_observation_processor,
                            teleop=teleop,
                            policy=policy,
                            policy_motion=cfg.policy_motion,
                            dataset_features=dataset_features,
                            preprocessor=preprocessor,
                            postprocessor=postprocessor,
                            dataset=dataset,
                            control_time_s=cfg.dataset.episode_time_s,
                            single_task=cfg.dataset.single_task,
                            display_data=cfg.display_data,
                            display_camera_names=display_camera_names,
                            display_compressed_images=display_compressed_images,
                            opencv_preview=opencv_preview,
                        )
                    except RecoverableObservationError as error:
                        if not _recover_observation_source(
                            robot=robot,
                            dataset=dataset,
                            events=events,
                            error=error,
                            play_sounds=cfg.play_sounds,
                            discard_episode=True,
                        ):
                            break
                        continue

                    # Execute a few seconds without recording to give time to manually reset the environment
                    # Skip reset for the last episode to be recorded
                    if not events["stop_recording"] and (
                        (recorded_episodes < cfg.dataset.num_episodes - 1) or events["rerecord_episode"]
                    ):
                        log_say("Reset the environment", cfg.play_sounds)

                        # reset g1 robot
                        if robot.name == "unitree_g1":
                            robot.reset()

                        try:
                            record_loop(
                                robot=robot,
                                events=events,
                                fps=cfg.dataset.fps,
                                teleop_action_processor=teleop_action_processor,
                                robot_action_processor=robot_action_processor,
                                robot_observation_processor=robot_observation_processor,
                                teleop=teleop,
                                control_time_s=cfg.dataset.reset_time_s,
                                single_task=cfg.dataset.single_task,
                                display_data=cfg.display_data,
                                display_camera_names=display_camera_names,
                                opencv_preview=opencv_preview,
                            )
                        except RecoverableObservationError as error:
                            if not _recover_observation_source(
                                robot=robot,
                                dataset=dataset,
                                events=events,
                                error=error,
                                play_sounds=cfg.play_sounds,
                                discard_episode=True,
                            ):
                                break
                            continue

                    if events["rerecord_episode"]:
                        log_say("Re-record episode", cfg.play_sounds)
                        events["rerecord_episode"] = False
                        events["exit_early"] = False
                        if dataset is not None:
                            dataset.clear_episode_buffer()
                        continue

                    if dataset is not None:
                        episode_metadata = (
                            robot.get_episode_metadata() if hasattr(robot, "get_episode_metadata") else None
                        )
                        dataset.save_episode(episode_metadata=episode_metadata)
                    recorded_episodes += 1
    finally:
        log_say("Stop recording" if cfg.recording_enabled else "Stop inference", cfg.play_sounds, blocking=True)

        if opencv_preview is not None:
            opencv_preview.close()

        if teleop and teleop.is_connected:
            try:
                teleop.disconnect()
            except Exception as error:
                logging.exception("Failed to disconnect the teleoperator cleanly.")
                cleanup_error = cleanup_error or error
        if robot.is_connected:
            try:
                robot.disconnect()
            except Exception as error:
                logging.exception("Failed to return the robot to zero or disconnect cleanly.")
                cleanup_error = cleanup_error or error

        if dataset:
            dataset.finalize()

        if not is_headless() and listener:
            listener.stop()

        if dataset is not None and cfg.dataset.push_to_hub:
            dataset.push_to_hub(tags=cfg.dataset.tags, private=cfg.dataset.private)

        log_say("Exiting", cfg.play_sounds)
        if cleanup_error is not None and sys.exc_info()[0] is None:
            raise cleanup_error
    return dataset


def main():
    register_third_party_plugins()
    record()


if __name__ == "__main__":
    main()
